import { spawnSync } from 'node:child_process';
import { createHash, randomUUID } from 'node:crypto';
import { appendFile, cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const pilots = ['software', 'embedded'];
const configurations = ['strong-single', 'same-model-workers', 'tiered-workers'];
const matrix = pilots.flatMap(pilot => configurations.flatMap(configuration =>
  [1, 2, 3].map(trial => ({ trial_id: `${pilot}/${configuration}/${trial}`, pilot, configuration, trial }))));
const help = `Usage:
  node scripts/evaluate.mjs matrix
  node scripts/evaluate.mjs run --runner <executable> --runner-args-json <JSON-array> --platform <name> --output <JSONL>
  node scripts/evaluate.mjs import --input <JSONL> --output <JSONL>
  node scripts/evaluate.mjs summarize --input <JSONL>
Optional run selectors: --pilot <software|embedded> --configuration <name> --trial <1|2|3>
Optional run timeout: --timeout-ms <milliseconds>; default 1800000.
The runner receives one JSON task on stdin and must emit one JSON result on stdout.
No model runs or successful benchmark results are generated by the matrix command.`;
const [command, ...args] = process.argv.slice(2);
const options = {};
for (let i = 0; i < args.length; i += 2) {
  if (!args[i]?.startsWith('--') || args[i + 1] === undefined) throw new Error(help);
  options[args[i].slice(2)] = args[i + 1];
}
const hash = content => createHash('sha256').update(content).digest('hex');
const numeric = value => typeof value === 'number' && Number.isFinite(value) && value >= 0 ? value : null;
const configurationPolicy = {
  'strong-single': 'One strong model performs the task. A separate review invocation uses the same model.',
  'same-model-workers': 'One coordinator and up to three workers use the same strong model; review is a separate invocation.',
  'tiered-workers': 'A strong coordinator delegates bounded tasks to economy/balanced workers; review is a separate strong invocation.',
};
function inside(dir, path) {
  const rel = relative(dir, resolve(dir, path));
  return rel !== '..' && !rel.startsWith(`..\\`) && !rel.startsWith('../') && !isAbsolute(rel);
}
function validateTrial(trial) {
  const expected = matrix.find(item => item.trial_id === trial.trial_id);
  if (trial.schema_version !== 1 || !expected || expected.pilot !== trial.pilot ||
      expected.configuration !== trial.configuration || expected.trial !== trial.trial ||
      !['accepted', 'failed', 'unverified'].includes(trial.status) ||
      !trial.provenance || typeof trial.provenance.platform !== 'string' ||
      !trial.artifacts || typeof trial.artifacts !== 'object' || Array.isArray(trial.artifacts) ||
      !trial.metrics || typeof trial.metrics !== 'object' || numeric(trial.elapsed_ms) === null) {
    throw new Error(`Invalid trial record: ${trial.trial_id ?? 'unknown'}`);
  }
  return trial;
}
async function readTrials(file, missingAllowed = false) {
  if (!file) throw new Error('A JSONL path is required.');
  let content;
  try { content = await readFile(resolve(file), 'utf8'); }
  catch (error) { if (missingAllowed && error.code === 'ENOENT') return []; throw error; }
  const trials = content.split(/\r?\n/).filter(line => line.trim()).map(line => validateTrial(JSON.parse(line)));
  if (new Set(trials.map(trial => trial.trial_id)).size !== trials.length) throw new Error('Duplicate trial IDs.');
  return trials;
}
async function appendTrial(file, trial) {
  await mkdir(dirname(resolve(file)), { recursive: true });
  await appendFile(resolve(file), `${JSON.stringify(trial)}\n`, 'utf8');
}
function median(values) {
  const available = values.filter(value => numeric(value) !== null).sort((a, b) => a - b);
  const mid = Math.floor(available.length / 2);
  return { observed: available.length, median: available.length ?
    (available.length % 2 ? available[mid] : (available[mid - 1] + available[mid]) / 2) : 'unavailable' };
}
async function run() {
  if (!options.runner || !options.platform || !options.output) throw new Error(help);
  const runnerArgs = JSON.parse(options['runner-args-json'] ?? '[]');
  if (!Array.isArray(runnerArgs) || !runnerArgs.every(arg => typeof arg === 'string')) throw new Error('Runner arguments must be a JSON array of strings.');
  const timeout = Number(options['timeout-ms'] ?? 1_800_000);
  if (!Number.isSafeInteger(timeout) || timeout < 1) throw new Error('timeout-ms must be a positive integer.');
  if (options.pilot && !pilots.includes(options.pilot)) throw new Error('Unknown pilot.');
  if (options.configuration && !configurations.includes(options.configuration)) throw new Error('Unknown configuration.');
  if (options.trial && !['1', '2', '3'].includes(options.trial)) throw new Error('trial must be 1, 2, or 3.');
  const completed = new Set((await readTrials(options.output, true)).map(trial => trial.trial_id));
  const selected = matrix.filter(item => (!options.pilot || item.pilot === options.pilot) &&
    (!options.configuration || item.configuration === options.configuration) &&
    (!options.trial || item.trial === Number(options.trial)) && !completed.has(item.trial_id));
  for (const item of selected) {
    const workspace = join(dirname(resolve(options.output)), 'workspaces',
      `${item.pilot}-${item.configuration}-${item.trial}-${randomUUID()}`);
    await mkdir(workspace, { recursive: true });
    await cp(join(root, 'examples', item.pilot), workspace, { recursive: true });
    const testFile = item.pilot === 'software' ? 'tests/config.test.mjs' : 'tests/controller.test.mjs';
    const protectedFiles = ['README.md', testFile];
    const protectedHashes = Object.fromEntries(await Promise.all(protectedFiles.map(async file => [file, hash(await readFile(join(workspace, file)))])));
    const sourceFile = item.pilot === 'software' ? 'config.mjs' : 'simulation.mjs';
    const original = await readFile(join(workspace, sourceFile), 'utf8');
    const constants = original.slice(0, original.indexOf('\nexport function'));
    // Strip the software imports and implementations; preserve only public defaults.
    const publicConstants = item.pilot === 'software' ? original.match(/export const DEFAULT_CONFIG[^\n]+/)[0] : constants;
    const names = item.pilot === 'software' ? ['validateConfig', 'loadConfig', 'saveConfig'] : ['controllerStep', 'operatingPoint', 'simulate'];
    await writeFile(join(workspace, sourceFile), `${publicConstants}\n${names.map(name => `export function ${name}() { throw new Error('Implement the documented pilot requirement.'); }`).join('\n')}\n`);
    if (item.pilot === 'embedded') await writeFile(join(workspace, 'controller.c'), '#include "controller.h"\n/* Implement the documented controller contract. */\n');
    const packet = { schema_version: 1, ...item, platform: options.platform, workspace,
      configuration_policy: configurationPolicy[item.configuration],
      goal: 'Implement this pilot from README.md. Preserve the provided requirements and tests. Record work, verification, limitations, and a separate review.',
      baseline: { protected_sha256: protectedHashes, reference_source_sha256: hash(original) },
      acceptance_command: [process.execPath, '--test', testFile],
      required_result: 'Return JSON with implementation_actor, review {status, actor, artifact}, metrics, requested_models, confirmed_models, and evidence. Use null for unobserved values.',
      metrics: ['retries', 'escalations', 'escaped_defects', 'human_correction_minutes', 'cost_amount', 'cost_currency', 'quota_consumed'],
      limitations: ['Automated acceptance covers the supplied tests; independent review is required for task acceptance.',
        'Embedded source compilation, real target execution, and physical hardware are separate evidence.'] };
    await writeFile(join(workspace, 'task-packet.json'), `${JSON.stringify(packet, null, 2)}\n`);
    const startedAt = new Date().toISOString();
    const start = performance.now();
    const runner = spawnSync(options.runner, runnerArgs, { cwd: workspace, input: JSON.stringify(packet),
      encoding: 'utf8', timeout, maxBuffer: 8 * 2 ** 20, shell: false });
    const elapsed = performance.now() - start;
    await writeFile(join(workspace, 'runner.stdout.log'), runner.stdout ?? '');
    await writeFile(join(workspace, 'runner.stderr.log'), runner.stderr ?? '');
    let response = {};
    let responseError = null;
    try {
      const value = JSON.parse(runner.stdout ?? '');
      if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error('Runner response must be a JSON object.');
      response = value;
    }
    catch (error) { responseError = error.message; }
    const unchanged = (await Promise.all(protectedFiles.map(async file => {
      try { return protectedHashes[file] === hash(await readFile(join(workspace, file))); }
      catch { return false; }
    }))).every(Boolean);
    const checks = spawnSync(process.execPath, ['--test', testFile], { cwd: workspace,
      encoding: 'utf8', timeout: 120_000, maxBuffer: 2 ** 20, shell: false });
    await writeFile(join(workspace, 'acceptance.stdout.log'), checks.stdout ?? '');
    await writeFile(join(workspace, 'acceptance.stderr.log'), checks.stderr ?? '');
    const review = response.review;
    let reviewed = false;
    if (review?.status === 'accepted' && typeof review.actor === 'string' && review.actor.length > 0 &&
        typeof response.implementation_actor === 'string' && response.implementation_actor.length > 0 &&
        review.actor !== response.implementation_actor && typeof review.artifact === 'string' && inside(workspace, review.artifact)) {
      try { reviewed = (await readFile(resolve(workspace, review.artifact), 'utf8')).trim().length > 0; } catch { /* unavailable */ }
    }
    const passed = runner.status === 0 && !responseError && checks.status === 0 && unchanged;
    const metrics = response.metrics ?? {};
    const trial = { schema_version: 1, ...item, source: 'native-runner',
      status: !passed ? 'failed' : reviewed ? 'accepted' : 'unverified',
      elapsed_ms: elapsed, started_at: startedAt, recorded_at: new Date().toISOString(),
      provenance: { platform: options.platform, runner: [options.runner, ...runnerArgs], workspace },
      requested_models: response.requested_models ?? 'unavailable', confirmed_models: response.confirmed_models ?? 'unavailable',
      metrics: { retries: numeric(metrics.retries), escalations: numeric(metrics.escalations),
        escaped_defects: numeric(metrics.escaped_defects), human_correction_minutes: numeric(metrics.human_correction_minutes),
        cost_amount: numeric(metrics.cost_amount), cost_currency: typeof metrics.cost_currency === 'string' ? metrics.cost_currency : null,
        quota_consumed: numeric(metrics.quota_consumed) },
      verification: { test_exit_code: checks.status, protected_files_unchanged: unchanged, independently_reviewed: reviewed,
        runner_exit_code: runner.status, runner_error: runner.error?.message ?? responseError },
      baseline: packet.baseline, artifacts: { task_packet: join(workspace, 'task-packet.json'),
        runner_stdout: join(workspace, 'runner.stdout.log'), runner_stderr: join(workspace, 'runner.stderr.log'),
        acceptance_stdout: join(workspace, 'acceptance.stdout.log'), acceptance_stderr: join(workspace, 'acceptance.stderr.log'),
        review: reviewed ? resolve(workspace, review.artifact) : null },
      review: review ?? 'unavailable', evidence: Array.isArray(response.evidence) ? response.evidence : [] };
    await appendTrial(options.output, trial);
    process.stdout.write(`${item.trial_id}: ${trial.status}\n`);
  }
}
async function summarize(file) {
  const trials = await readTrials(file);
  return { schema_version: 1, planned_trials: matrix.length, recorded_trials: trials.length,
    unrecorded_trials: matrix.filter(item => !trials.some(trial => trial.trial_id === item.trial_id)).map(item => item.trial_id),
    groups: pilots.flatMap(pilot => configurations.map(configuration => {
      const group = trials.filter(trial => trial.pilot === pilot && trial.configuration === configuration);
      const currencies = [...new Set(group.filter(trial => numeric(trial.metrics?.cost_amount) !== null &&
        trial.metrics?.cost_currency).map(trial => trial.metrics.cost_currency))];
      return { pilot, configuration, planned: 3, recorded: group.length,
        accepted: group.filter(trial => trial.status === 'accepted').length,
        failed: group.filter(trial => trial.status === 'failed').length,
        unverified: group.filter(trial => trial.status === 'unverified').length,
        acceptance_rate: group.length ? group.filter(trial => trial.status === 'accepted').length / group.length : 'unavailable',
        elapsed_ms: median(group.map(trial => trial.elapsed_ms)),
        retries: median(group.map(trial => trial.metrics?.retries)),
        escalations: median(group.map(trial => trial.metrics?.escalations)),
        escaped_defects: median(group.map(trial => trial.metrics?.escaped_defects)),
        human_correction_minutes: median(group.map(trial => trial.metrics?.human_correction_minutes)),
        cost: currencies.length === 1 ? { currency: currencies[0], ...median(group.filter(trial => trial.metrics?.cost_currency === currencies[0]).map(trial => trial.metrics?.cost_amount)) }
          : { observed: 0, median: 'unavailable', reason: currencies.length ? 'Mixed currencies.' : 'No recorded cost.' },
        quota_consumed: median(group.map(trial => trial.metrics?.quota_consumed)),
        sources: [...new Set(group.map(trial => trial.source))] };
    })),
    limitations: ['Imported observations are reported data, not authenticated platform telemetry.',
      'Review artifact presence verifies recorded separation, not review quality.',
      'Three trials per group support a pilot comparison, not a broad optimization claim.'] };
}
async function main() {
  if (command === 'matrix') return { schema_version: 1, status: 'not-run', trials: matrix };
  if (command === 'run') { await run(); return null; }
  if (command === 'summarize') return summarize(options.input);
  if (command === 'import') {
    const incoming = await readTrials(options.input);
    const existing = await readTrials(options.output, true);
    const ids = new Set(existing.map(trial => trial.trial_id));
    if (incoming.some(trial => ids.has(trial.trial_id))) throw new Error('Import would duplicate existing trial IDs.');
    for (const trial of incoming) await appendTrial(options.output, { ...trial, source: 'imported-record',
      import_provenance: { input: resolve(options.input), imported_at: new Date().toISOString(), original_source: trial.source ?? 'unavailable' } });
    return { imported: incoming.length, output: resolve(options.output) };
  }
  throw new Error(help);
}
main().then(value => { if (value !== null) process.stdout.write(`${JSON.stringify(value, null, 2)}\n`); })
  .catch(error => { process.stderr.write(`${error.message}\n`); process.exitCode = 1; });
